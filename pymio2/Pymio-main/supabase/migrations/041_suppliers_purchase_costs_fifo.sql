CREATE OR REPLACE FUNCTION public.pymio_set_initial_product_cost() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public,pg_temp AS $$
BEGIN NEW.initial_cost:=NEW.cost; RETURN NEW; END $$;
DROP TRIGGER IF EXISTS products_initial_cost ON public.products;
CREATE TRIGGER products_initial_cost BEFORE INSERT ON public.products FOR EACH ROW EXECUTE FUNCTION public.pymio_set_initial_product_cost();

CREATE TABLE IF NOT EXISTS public.inventory_cost_layers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint NOT NULL REFERENCES public.companies(id),
  product_id bigint NOT NULL,
  source_line_id bigint REFERENCES public.movement_lines(id) ON DELETE CASCADE,
  acquired_at timestamptz NOT NULL,
  original_units integer NOT NULL CHECK (original_units > 0),
  remaining_units integer NOT NULL CHECK (remaining_units BETWEEN 0 AND original_units),
  unit_cost numeric NOT NULL CHECK (unit_cost BETWEEN 0 AND 2147483647),
  FOREIGN KEY (product_id) REFERENCES public.products(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS inventory_cost_layers_fifo ON public.inventory_cost_layers(company_id, product_id, acquired_at, id) WHERE remaining_units > 0;
