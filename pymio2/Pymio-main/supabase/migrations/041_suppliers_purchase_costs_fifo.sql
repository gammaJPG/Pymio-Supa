CREATE TABLE IF NOT EXISTS public.suppliers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint NOT NULL REFERENCES public.companies(id),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  phone text CHECK (phone IS NULL OR (length(phone) <= 32 AND phone ~ '^\+?[0-9 ().-]+$' AND length(regexp_replace(phone, '[^0-9]', '', 'g')) BETWEEN 7 AND 15)),
  email text CHECK (email IS NULL OR (length(email) <= 254 AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')),
  address text CHECK (address IS NULL OR length(address) <= 300),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, id)
);
CREATE INDEX IF NOT EXISTS suppliers_company_name ON public.suppliers(company_id, name, id);
ALTER TABLE public.suppliers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.suppliers FROM PUBLIC, anon, authenticated;
