CREATE OR REPLACE FUNCTION public.pymio_supplier(company bigint, payload jsonb, method text) RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE supplier public.suppliers;
BEGIN
  IF method = 'list' THEN
    RETURN (SELECT coalesce(jsonb_agg(jsonb_build_object(
      'id', s.id::text, 'name', s.name, 'phone', s.phone, 'email', s.email, 'address', s.address,
      'costs', coalesce((SELECT jsonb_object_agg(c.product_id::text, c.default_cost) FROM public.supplier_product_costs c WHERE c.company_id=company AND c.supplier_id=s.id), '{}'::jsonb)
    ) ORDER BY s.name, s.id), '[]'::jsonb) FROM public.suppliers s WHERE s.company_id=company);
  ELSIF method = 'create' THEN
    INSERT INTO public.suppliers(company_id,name,phone,email,address)
    VALUES(company,btrim(payload->>'name'),nullif(btrim(payload->>'phone'),''),nullif(btrim(payload->>'email'),''),nullif(btrim(payload->>'address'),''))
    RETURNING * INTO supplier;
    RETURN jsonb_build_object('id',supplier.id::text,'name',supplier.name,'phone',supplier.phone,'email',supplier.email,'address',supplier.address,'costs','{}'::jsonb);
  END IF;
  RAISE SQLSTATE 'PT400' USING MESSAGE='Operación de proveedor inválida.';
END $$;

CREATE OR REPLACE FUNCTION public.pymio_rebuild_fifo(company bigint) RETURNS void
LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE p public.products; entry record; layer record; bootstrap bigint; pending integer; taken integer; total numeric;
BEGIN
  DELETE FROM public.movement_fifo_allocations a USING public.movement_lines l WHERE l.id=a.movement_line_id AND l.company_id=company;
  DELETE FROM public.inventory_cost_layers WHERE company_id=company;
  UPDATE public.movement_lines SET fifo_unit_cost=NULL,fifo_total_cost=NULL WHERE company_id=company;
  FOR p IN SELECT * FROM public.products WHERE company_id=company ORDER BY id LOOP
    SELECT p.qty::bigint-coalesce(sum(l.units),0) INTO bootstrap
      FROM public.movement_lines l JOIN public.movements m ON m.code=l.movement_code
      WHERE l.company_id=company AND l.product_id=p.id AND m.deleted_at IS NULL;
    IF bootstrap<0 OR bootstrap>2147483647 THEN RAISE SQLSTATE 'PT409' USING MESSAGE='No se pudo reconstruir el costo FIFO de '||p.sku||'.'; END IF;
    IF bootstrap>0 THEN
      INSERT INTO public.inventory_cost_layers(company_id,product_id,acquired_at,original_units,remaining_units,unit_cost)
      VALUES(company,p.id,p.created_at,bootstrap,bootstrap,p.initial_cost);
    END IF;
    FOR entry IN SELECT l.*,m.operation,m.operation_detail,m.created_at AS movement_created
      FROM public.movement_lines l JOIN public.movements m ON m.code=l.movement_code
      WHERE l.company_id=company AND l.product_id=p.id AND m.deleted_at IS NULL
      ORDER BY m.occurred_at,m.created_at,m.code,l.id
    LOOP
      IF entry.units>0 THEN
        INSERT INTO public.inventory_cost_layers(company_id,product_id,source_line_id,acquired_at,original_units,remaining_units,unit_cost)
        VALUES(company,p.id,entry.id,entry.occurred_at,entry.units,entry.units,CASE WHEN entry.operation_detail='Compra' THEN entry.unit_price ELSE p.cost END);
      ELSE
        pending:=abs(entry.units); total:=0;
        FOR layer IN SELECT * FROM public.inventory_cost_layers WHERE company_id=company AND product_id=p.id AND remaining_units>0 ORDER BY acquired_at,id FOR UPDATE LOOP
          EXIT WHEN pending=0; taken:=least(pending,layer.remaining_units);
          INSERT INTO public.movement_fifo_allocations(movement_line_id,layer_id,units,unit_cost) VALUES(entry.id,layer.id,taken,layer.unit_cost);
          UPDATE public.inventory_cost_layers SET remaining_units=remaining_units-taken WHERE id=layer.id;
          pending:=pending-taken; total:=total+taken*layer.unit_cost;
        END LOOP;
        IF pending>0 THEN RAISE SQLSTATE 'PT409' USING MESSAGE='Stock FIFO insuficiente para '||p.sku||'.'; END IF;
        UPDATE public.movement_lines SET fifo_total_cost=total,fifo_unit_cost=total/abs(entry.units) WHERE id=entry.id;
      END IF;
    END LOOP;
  END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public.pymio_list(company bigint, payload jsonb) RETURNS jsonb
LANGUAGE sql SECURITY INVOKER SET search_path = public, pg_temp AS $fn$
SELECT coalesce(jsonb_agg(to_jsonb(r)), '[]'::jsonb) FROM (
WITH recent AS (
    SELECT * FROM public.movements WHERE company_id=company AND deleted_at IS NULL AND ((payload->>'code')::text IS NULL OR display_code=(payload->>'code')) AND ((payload->>'from')::timestamptz IS NULL OR occurred_at >= (payload->>'from')::timestamptz) AND ((payload->>'to')::timestamptz IS NULL OR occurred_at < (payload->>'to')::timestamptz) ORDER BY created_at DESC, code LIMIT 500
  ), grouped AS (
    SELECT m.code,m.display_code,m.operation,m.operation_detail,m.channel,m.payment_method,m.occurred_at,m.created_at,m.discount_type,m.discount_value,m.discount_scope,m.revision,m."Estado",m.supplier_id,
      COUNT(DISTINCT l.product_id)::integer AS product_count,SUM(l.unit_price*ABS(l.units::numeric)) AS subtotal,
      SUM(CASE WHEN l.discount_type='percentage' THEN l.unit_price*ABS(l.units::numeric)*l.discount_value/100 WHEN l.discount_type='fixed' THEN l.discount_value ELSE 0 END) AS line_discount_amount,
      jsonb_agg(jsonb_build_object('product_id',l.product_id::text,'sku',l.sku,'name',l.product_name,'unit_price',l.unit_price,'unit_cost',CASE WHEN m.operation_detail='Compra' THEN l.unit_price ELSE l.fifo_unit_cost END,'fifo_unit_cost',l.fifo_unit_cost,'fifo_total_cost',l.fifo_total_cost,'discount_type',l.discount_type,'discount_value',l.discount_value,'discount_amount',(CASE WHEN l.discount_type='percentage' THEN l.unit_price*ABS(l.units::numeric)*l.discount_value/100 WHEN l.discount_type='fixed' THEN l.discount_value ELSE 0 END),'net_total',l.unit_price*ABS(l.units::numeric)-(CASE WHEN l.discount_type='percentage' THEN l.unit_price*ABS(l.units::numeric)*l.discount_value/100 WHEN l.discount_type='fixed' THEN l.discount_value ELSE 0 END),'total',l.unit_price*ABS(l.units::numeric),'initial_qty',l.initial_qty,'units',l.units,'final_qty',l.final_qty) ORDER BY l.id) AS products
    FROM recent m JOIN public.movement_lines l ON l.movement_code=m.code GROUP BY m.code,m.display_code,m.operation,m.operation_detail,m.channel,m.payment_method,m.occurred_at,m.created_at,m.discount_type,m.discount_value,m.discount_scope,m.revision,m."Estado",m.supplier_id
  ) SELECT display_code AS code,revision,"Estado",operation,operation_detail,channel,payment_method,occurred_at,product_count,subtotal,discount_type,discount_value,discount_scope,supplier_id::text,
    CASE WHEN discount_scope='product' THEN line_discount_amount WHEN discount_type='percentage' THEN subtotal*discount_value/100 WHEN discount_type='fixed' THEN discount_value ELSE 0 END AS discount_amount,
    subtotal-CASE WHEN discount_scope='product' THEN line_discount_amount WHEN discount_type='percentage' THEN subtotal*discount_value/100 WHEN discount_type='fixed' THEN discount_value ELSE 0 END AS total,products
    FROM grouped ORDER BY created_at DESC,code) r;
$fn$;

CREATE OR REPLACE FUNCTION public.pymio_api(operation text, company bigint, payload jsonb DEFAULT '{}') RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE result jsonb; selected_customer bigint; selected_supplier bigint; request jsonb; item jsonb; movement_id uuid;
BEGIN
  IF company IS NULL OR company<1 THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Empresa inválida.'; END IF;
  IF operation IN ('product.list','product.history','product.create','product.update','product.delete','product.status') THEN RETURN public.pymio_product(company,payload,split_part(operation,'.',2));
  ELSIF operation IN ('category.get','category.post','category.put','category.delete') THEN RETURN public.pymio_category(company,payload,split_part(operation,'.',2));
  ELSIF operation IN ('customer.list','customer.create') THEN RETURN public.pymio_customer(company,payload,split_part(operation,'.',2));
  ELSIF operation IN ('supplier.list','supplier.create') THEN RETURN public.pymio_supplier(company,payload,split_part(operation,'.',2));
  ELSIF operation='movement.list' THEN
    RETURN (SELECT coalesce(jsonb_agg(entry||jsonb_build_object('customer_id',m.customer_id::text,'customer_name',c.name,'supplier_id',m.supplier_id::text,'supplier_name',s.name) ORDER BY ord),'[]'::jsonb)
      FROM jsonb_array_elements(public.pymio_list(company,payload)) WITH ORDINALITY AS listed(entry,ord)
      LEFT JOIN public.movements m ON m.company_id=company AND m.display_code=entry->>'code'
      LEFT JOIN public.customers c ON c.company_id=company AND c.id=m.customer_id
      LEFT JOIN public.suppliers s ON s.company_id=company AND s.id=m.supplier_id);
  ELSIF operation IN ('movement.create','movement.change') THEN
    request:=CASE WHEN operation='movement.create' THEN payload->'request' ELSE payload->'replacement' END;
    IF request IS NOT NULL AND request<>'null'::jsonb THEN
      IF request->>'customer_id' IS NOT NULL THEN
        IF request->>'operation_detail' IS DISTINCT FROM 'Venta' OR request->>'customer_id' !~ '^[1-9][0-9]{0,18}$' THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Selecciona un cliente válido para la venta.'; END IF;
        selected_customer:=(request->>'customer_id')::bigint;
        IF NOT EXISTS(SELECT 1 FROM public.customers WHERE company_id=company AND id=selected_customer) THEN RAISE SQLSTATE 'PT400' USING MESSAGE='El cliente no existe o no pertenece a esta empresa.'; END IF;
      END IF;
      IF request->>'operation_detail'='Compra' THEN
        IF request->>'supplier_id' IS NOT NULL THEN
          IF request->>'supplier_id' !~ '^[1-9][0-9]{0,18}$' THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Selecciona un proveedor válido para la compra.'; END IF;
          selected_supplier:=(request->>'supplier_id')::bigint;
          IF NOT EXISTS(SELECT 1 FROM public.suppliers WHERE company_id=company AND id=selected_supplier) THEN RAISE SQLSTATE 'PT400' USING MESSAGE='El proveedor no existe o no pertenece a esta empresa.'; END IF;
        END IF;
        FOR item IN SELECT value FROM jsonb_array_elements(request->'items') LOOP
          IF item->>'unit_cost' IS NULL OR (item->>'unit_cost') !~ '^[0-9]{1,10}$' OR (item->>'unit_cost')::numeric>2147483647 THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Ingresa un costo válido para cada producto comprado.'; END IF;
        END LOOP;
      ELSIF request->>'supplier_id' IS NOT NULL THEN RAISE SQLSTATE 'PT400' USING MESSAGE='Los proveedores solo se seleccionan en compras.';
      END IF;
    END IF;
    result:=public.pymio_movement(company,payload,split_part(operation,'.',2));
    IF request IS NOT NULL AND request<>'null'::jsonb THEN
      IF operation='movement.create' THEN movement_id:=(payload->>'code')::uuid;
      ELSE SELECT code INTO movement_id FROM public.movements WHERE company_id=company AND display_code=payload->>'displayCode' AND deleted_at IS NULL;
      END IF;
      UPDATE public.movements SET customer_id=selected_customer,supplier_id=selected_supplier WHERE company_id=company AND code=movement_id;
      IF request->>'operation_detail'='Compra' THEN
        FOR item IN SELECT value FROM jsonb_array_elements(request->'items') LOOP
          UPDATE public.movement_lines SET unit_price=(item->>'unit_cost')::integer WHERE movement_code=movement_id AND product_id=(item->>'product_id')::bigint;
          UPDATE public.products SET cost=(item->>'unit_cost')::integer,updated_at=now() WHERE company_id=company AND id=(item->>'product_id')::bigint;
          IF selected_supplier IS NOT NULL THEN
            INSERT INTO public.supplier_product_costs(company_id,supplier_id,product_id,default_cost) VALUES(company,selected_supplier,(item->>'product_id')::bigint,(item->>'unit_cost')::integer)
              ON CONFLICT(company_id,supplier_id,product_id) DO UPDATE SET default_cost=excluded.default_cost,updated_at=now();
          END IF;
        END LOOP;
      END IF;
    END IF;
    PERFORM public.pymio_rebuild_fifo(company);
    RETURN result;
  END IF;
  RAISE SQLSTATE 'PT400' USING MESSAGE='Operación inválida.';
END $$;

REVOKE ALL ON FUNCTION public.pymio_supplier(bigint,jsonb,text), public.pymio_rebuild_fifo(bigint), public.pymio_set_initial_product_cost() FROM PUBLIC, anon, authenticated;
