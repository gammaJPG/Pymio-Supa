CREATE TABLE IF NOT EXISTS public.movement_fifo_allocations (
  movement_line_id bigint NOT NULL REFERENCES public.movement_lines(id) ON DELETE CASCADE,
  layer_id bigint NOT NULL REFERENCES public.inventory_cost_layers(id) ON DELETE CASCADE,
  units integer NOT NULL CHECK (units > 0),
  unit_cost numeric NOT NULL CHECK (unit_cost BETWEEN 0 AND 2147483647),
  PRIMARY KEY (movement_line_id, layer_id)
